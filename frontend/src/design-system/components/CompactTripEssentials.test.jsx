import React from 'react';
import { afterEach, beforeEach, expect, test, vi } from 'vitest';
import { cleanup, fireEvent, render, screen } from '@testing-library/react';
import userEvent from '@testing-library/user-event';
import { CompactTripEssentials } from './CompactTripEssentials';
const data = { status: 'ready', dates: { start: '2026-11-12', end: '2026-11-16', flexible: false, note: '' }, travelers: 2, budget: { label: '€1,900', noFixedBudget: false } };
beforeEach(() => {
  HTMLDialogElement.prototype.showModal = function () { this.open = true; };
  HTMLDialogElement.prototype.close = function () { this.open = false; };
});
afterEach(cleanup);
test('edits only dates, validates their order, and preserves newer unrelated data', async () => {
  const user = userEvent.setup(), action = vi.fn();
  const { rerender } = render(<CompactTripEssentials data={data} onAction={action}/>);
  await user.click(screen.getByRole('button', { name: 'Edit dates' }));
  expect(screen.queryByRole('spinbutton')).toBeNull();
  expect(screen.queryByLabelText('Budget')).toBeNull();
  fireEvent.change(screen.getByLabelText('End date'), { target: { value: '2026-11-10' } });
  fireEvent.submit(screen.getByRole('dialog').querySelector('form'));
  expect(screen.getByRole('alert').textContent).toBe('End date must follow start.');
  fireEvent.change(screen.getByLabelText('End date'), { target: { value: '2026-11-18' } });
  rerender(<CompactTripEssentials data={{ ...data, travelers: 4 }} onAction={action}/>);
  await user.click(screen.getByRole('button', { name: 'Update dates' }));
  expect(action).toHaveBeenCalledWith('edit_essentials', { ...data, travelers: 4, dates: { ...data.dates, end: '2026-11-18' } });
  expect(screen.queryByRole('dialog')).toBeNull();
  expect(document.activeElement).toBe(screen.getByRole('button', { name: 'Edit dates' }));
});
test('traveler stepper keeps its bounds and cancel discards changes', async () => {
  const user = userEvent.setup(), action = vi.fn();
  render(<CompactTripEssentials data={{ ...data, travelers: 1 }} onAction={action}/>);
  await user.click(screen.getByRole('button', { name: 'Edit travelers' }));
  expect(screen.getByRole('button', { name: 'Remove one traveler' }).disabled).toBe(true);
  await user.click(screen.getByRole('button', { name: 'Add one traveler' }));
  expect(screen.getByRole('spinbutton').value).toBe('2');
  fireEvent.change(screen.getByRole('spinbutton'), { target: { value: '50' } });
  expect(screen.getByRole('button', { name: 'Add one traveler' }).disabled).toBe(true);
  await user.click(screen.getByRole('button', { name: 'Cancel' }));
  expect(action.mock.calls.filter(([name]) => name === 'edit_essentials')).toHaveLength(0);
  await user.click(screen.getByRole('button', { name: 'Edit travelers' }));
  expect(screen.getByRole('spinbutton').value).toBe('1');
  await user.click(screen.getByRole('button', { name: 'Add one traveler' }));
  await user.click(screen.getByRole('button', { name: 'Update travelers' }));
  expect(action).toHaveBeenCalledWith('edit_essentials', { ...data, travelers: 2 });
});
test('budget and flexible dates produce valid explicit draft updates; Escape cancels', async () => {
  const user = userEvent.setup(), action = vi.fn();
  render(<CompactTripEssentials data={data} onAction={action}/>);
  await user.click(screen.getByRole('button', { name: 'Edit budget' }));
  await user.click(screen.getByLabelText('No fixed budget'));
  expect(screen.queryByLabelText('Budget')).toBeNull();
  await user.click(screen.getByRole('button', { name: 'Update budget' }));
  expect(action).toHaveBeenCalledWith('edit_essentials', { ...data, budget: { label: '', noFixedBudget: true } });
  await user.click(screen.getByRole('button', { name: 'Edit dates' }));
  await user.click(screen.getByLabelText('My dates are flexible'));
  expect(screen.queryByLabelText('Start date')).toBeNull();
  await user.click(screen.getByRole('button', { name: 'Update dates' }));
  expect(action).toHaveBeenCalledWith('edit_essentials', { ...data, dates: { start: '', end: '', note: '', flexible: true } });
  const saved = action.mock.calls.filter(([name]) => name === 'edit_essentials').length;
  await user.click(screen.getByRole('button', { name: 'Edit budget' }));
  await user.clear(screen.getByLabelText('Budget'));
  fireEvent(screen.getByRole('dialog'), new Event('cancel', { bubbles: true, cancelable: true }));
  expect(screen.queryByRole('dialog')).toBeNull();
  expect(action.mock.calls.filter(([name]) => name === 'edit_essentials')).toHaveLength(saved);
});
